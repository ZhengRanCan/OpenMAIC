import { beforeEach, expect, it, vi } from 'vitest';
import type { ServerPersistenceProvider } from '@/lib/persistence/server-provider';
import type { OwnerPrincipal } from '@/lib/server/identity/types';
import type { ResolvedModel } from '@/lib/server/resolve-model';
import type {
  EvidenceRun,
  EvidenceSettings,
  OrganizeEvidenceRequest,
} from '@/lib/evidence/contracts';
const m = vi.hoisted(() => ({
  lookupRequest: vi.fn(),
  reserve: vi.fn(),
  claim: vi.fn(),
  capture: vi.fn(),
  finalize: vi.fn(),
  interrupt: vi.fn(),
  read: vi.fn(),
  llm: vi.fn(),
}));
vi.mock('@/lib/persistence/quiz-evidence-store', () => ({
  QuizEvidenceStore: class {
    lookupRequest = m.lookupRequest;
    reserve = m.reserve;
    claim = m.claim;
    capture = m.capture;
    finalize = m.finalize;
    interrupt = m.interrupt;
  },
}));
vi.mock('@/lib/persistence/quiz-evidence-read', () => ({ readEvidenceRun: m.read }));
vi.mock('@/lib/ai/llm', () => ({ callLLM: m.llm }));
import { organizeQuizEvidence, evidenceModelIdentity } from '@/lib/server/quiz-evidence';
const provider = {} as ServerPersistenceProvider;
const principal: OwnerPrincipal = {
  ownerId: 'owner',
  kind: 'user',
  roles: new Set(),
  assurance: 'verified',
};
const request: OrganizeEvidenceRequest = {
  operationId: crypto.randomUUID(),
  stageId: 'stage',
  anchor: { attemptId: 'a', submissionId: 's' },
  related: [],
  language: 'zh-CN',
  action: 'reuse-or-create',
};
const model = {
  model: {},
  providerId: 'test',
  modelId: 'model',
  baseUrl: 'https://example.invalid/private-key',
  serverManaged: true,
} as ResolvedModel;
const resolve = vi.fn(async () => model),
  settings = vi.fn(async () => ({}) as EvidenceSettings);
const run = (state: EvidenceRun['state'] = 'reserved') =>
  ({
    id: 'run',
    stageId: 'stage',
    state,
    context: { text: 'context' },
    prompt: { system: 'system' },
    modelIdentity: evidenceModelIdentity(model),
    semanticStatus: 'unreviewed',
    adoptionAllowed: false,
  }) as EvidenceRun;
beforeEach(() => {
  Object.values(m).forEach((x) => x.mockReset());
  resolve.mockClear();
  settings.mockClear();
  m.read.mockResolvedValue({
    id: 'run',
    visibility: 'visible',
    semanticStatus: 'unreviewed',
    adoptionAllowed: false,
  });
  m.capture.mockResolvedValue('owner');
  m.claim.mockResolvedValue({
    runId: 'run',
    token: 'token',
    leaseExpiresAt: new Date(Date.now() + 240000).toISOString(),
  });
  m.lookupRequest.mockResolvedValue(null);
  m.reserve.mockResolvedValue({ kind: 'reserved', run: run() });
  m.llm.mockResolvedValue({ text: '{}', finishReason: 'stop', usage: { totalTokens: 10 } });
});
it('calls once with bounded settings then saves/finalizes and projects', async () => {
  const result = await organizeQuizEvidence(provider, principal, request, resolve, settings);
  expect(result.status).toBe(201);
  expect(m.llm).toHaveBeenCalledOnce();
  const [args, source, retry, thinking, fallback] = m.llm.mock.calls[0];
  expect(args).toMatchObject({
    maxOutputTokens: 16000,
    maxRetries: 0,
    prompt: 'context',
    system: 'system',
  });
  expect(args.tools).toBeUndefined();
  expect(source).toBe('quiz-evidence');
  expect(retry).toEqual({ retries: 0 });
  expect(thinking).toEqual({ mode: 'default' });
  expect(fallback.enabled).toBe(false);
  expect(m.capture).toHaveBeenCalledOnce();
  expect(m.finalize).toHaveBeenCalledWith('owner', 'run');
  expect(result.run.adoptionAllowed).toBe(false);
});
it.each(['completed', 'partial', 'failed'] as const)(
  'replays %s without resolving settings/model',
  async (state) => {
    m.lookupRequest.mockResolvedValue(run(state));
    await organizeQuizEvidence(provider, principal, request, resolve, settings);
    expect(resolve).not.toHaveBeenCalled();
    expect(settings).not.toHaveBeenCalled();
    expect(m.llm).not.toHaveBeenCalled();
  },
);
it('recovers generated bytes without paying again', async () => {
  m.lookupRequest.mockResolvedValue(run('generated'));
  await organizeQuizEvidence(provider, principal, request, resolve, settings);
  expect(m.finalize).toHaveBeenCalledOnce();
  expect(m.llm).not.toHaveBeenCalled();
  expect(resolve).not.toHaveBeenCalled();
});
it('marks expired calling unknown with no repeated generation', async () => {
  m.lookupRequest.mockResolvedValue({
    ...run('calling'),
    leaseExpiresAt: new Date(0).toISOString(),
  });
  await expect(
    organizeQuizEvidence(provider, principal, request, resolve, settings),
  ).rejects.toMatchObject({ code: 'INVOCATION_RESULT_UNKNOWN' });
  expect(m.interrupt).toHaveBeenCalledOnce();
  expect(m.llm).not.toHaveBeenCalled();
});
it('claim loser never calls a model', async () => {
  m.claim.mockResolvedValue(null);
  expect((await organizeQuizEvidence(provider, principal, request, resolve, settings)).status).toBe(
    202,
  );
  expect(m.llm).not.toHaveBeenCalled();
});
it('a second concurrent request cannot invoke again while the winner awaits a slow model', async () => {
  let announceStart!: () => void;
  let completeCall!: (value: { text: string; finishReason: string; usage: object }) => void;
  const started = new Promise<void>((resolve) => {
    announceStart = resolve;
  });
  m.claim
    .mockResolvedValueOnce({
      runId: 'run',
      token: 'token',
      leaseExpiresAt: new Date(Date.now() + 240000).toISOString(),
    })
    .mockResolvedValue(null);
  m.llm.mockImplementation(() => {
    announceStart();
    return new Promise((resolve) => {
      completeCall = resolve;
    });
  });
  const first = organizeQuizEvidence(provider, principal, request, resolve, settings);
  await started;
  const second = await organizeQuizEvidence(provider, principal, request, resolve, settings);
  expect(second.status).toBe(202);
  expect(m.llm).toHaveBeenCalledOnce();
  completeCall({ text: '{}', finishReason: 'stop', usage: {} });
  await first;
  expect(m.llm).toHaveBeenCalledOnce();
});
it('uses the fixed timeout and forwards only the protected view after completion', async () => {
  const timeout = vi.spyOn(AbortSignal, 'timeout');
  const hidden = {
    runId: 'run',
    state: 'completed',
    visibility: 'source-unavailable',
    reasonCode: 'SOURCE_UNAVAILABLE',
    semanticStatus: 'unreviewed',
    adoptionAllowed: false,
  };
  m.read.mockResolvedValue(hidden);
  try {
    const result = await organizeQuizEvidence(provider, principal, request, resolve, settings);
    expect(timeout).toHaveBeenCalledWith(180000);
    expect(result.run).toEqual(hidden);
    expect(result.run).not.toHaveProperty('context');
    expect(result.run).not.toHaveProperty('reply');
  } finally {
    timeout.mockRestore();
  }
});
it('captures a sanitized failed call and never retries it', async () => {
  m.llm.mockRejectedValue(new Error('secret provider URL'));
  await organizeQuizEvidence(provider, principal, request, resolve, settings);
  expect(m.llm).toHaveBeenCalledOnce();
  expect(m.capture.mock.calls[0][2]).toMatchObject({ text: '', finishReason: 'error' });
  expect(JSON.stringify(m.capture.mock.calls)).not.toContain('secret provider');
});
it('retries saving the same reply, without regenerating', async () => {
  m.capture.mockRejectedValueOnce(new Error('temporary DB failure')).mockResolvedValue('owner');
  await organizeQuizEvidence(provider, principal, request, resolve, settings);
  expect(m.capture).toHaveBeenCalledTimes(2);
  expect(m.capture.mock.calls[0][2]).toBe(m.capture.mock.calls[1][2]);
  expect(m.llm).toHaveBeenCalledOnce();
});
it('forwards finalization after claim but never returns content to old owner', async () => {
  m.capture.mockResolvedValue('new-owner');
  await expect(
    organizeQuizEvidence(provider, principal, request, resolve, settings),
  ).rejects.toMatchObject({ code: 'OWNER_CHANGED' });
  expect(m.finalize).toHaveBeenCalledWith('new-owner', 'run');
  expect(m.read).not.toHaveBeenCalled();
});
it('does not change the model of an already reserved run', async () => {
  m.lookupRequest.mockResolvedValue({
    ...run(),
    modelIdentity: { ...evidenceModelIdentity(model), model: 'old' },
  });
  await expect(
    organizeQuizEvidence(provider, principal, request, resolve, settings),
  ).rejects.toMatchObject({ code: 'MODEL_CONFIG_CHANGED' });
  expect(m.llm).not.toHaveBeenCalled();
});
it('stores endpoint fingerprints without the endpoint text or API key', () => {
  expect(JSON.stringify(evidenceModelIdentity({ ...model, apiKey: 'dont-save' }))).not.toMatch(
    /private-key|dont-save/,
  );
});
